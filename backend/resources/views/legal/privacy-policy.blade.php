        function setLanguage(lang) {
            const arSec = document.getElementById('section-ar');
            const enSec = document.getElementById('section-en');
            const btns = document.querySelectorAll('.lang-btn');
            const pageTitle = document.getElementById('page-title');

            if (lang === 'ar') {
                document.documentElement.setAttribute('lang', 'ar');
                document.documentElement.setAttribute('dir', 'rtl');
                arSec.classList.remove('hidden');
                enSec.classList.add('hidden');
                pageTitle.innerText = 'سياسة الخصوصية والشروط';
                btns[0].classList.add('active');
                btns[1].classList.remove('active');
            } else {
                document.documentElement.setAttribute('lang', 'en');
                document.documentElement.setAttribute('dir', 'ltr');
                arSec.classList.add('hidden');
                enSec.classList.remove('hidden');
                pageTitle.innerText = 'Privacy Policy & Terms';
                btns[0].classList.remove('active');
                btns[1].classList.add('active');
            }
        }
